import assert from 'node:assert/strict';
import {SpeechSegmenter, encodeWav} from '../app/static/voice-capture.js';
let starts=[], clips=[];
const segmenter=new SpeechSegmenter(1000, interrupting=>starts.push(interrupting), pcm=>clips.push(pcm));
const feed=(n,value,options={})=>{for(let i=0;i<n;i++)segmenter.push(new Float32Array(20).fill(value),options);};
feed(30,0,{interrupting:true});feed(5,.1,{interrupting:true});feed(10,0,{interrupting:true});
assert.equal(starts.length,0,'A short click must not interrupt');
feed(14,.1,{interrupting:true});assert.deepEqual(starts,[true]);
feed(20,.1);feed(46,0);assert.equal(clips.length,1);
assert.ok(clips[0].filter(v=>v>.09).length>=680,'Keep onset audio before interruption');
assert.equal(segmenter.active,false);
feed(30,.2,{enabled:false});assert.equal(starts.length,1,'Do not capture during STT');
feed(8,.2);assert.deepEqual(starts,[true,false]);
segmenter.reset();assert.equal(segmenter.active,false);
feed(1500,0);assert.ok(segmenter.recentSamples<=28000,'Bound manual recording memory');
segmenter.flush();assert.equal(clips.length,2);
const wav=await encodeWav(new Float32Array([-1,0,1]),48000).arrayBuffer();
const view=new DataView(wav);assert.equal(view.getUint32(24,true),48000);assert.equal(view.getInt16(44,true),-32768);assert.equal(view.getInt16(48,true),32767);
console.log('Voice onset, interrupt threshold, silence, pause, buffer bounds and WAV checks passed.');
